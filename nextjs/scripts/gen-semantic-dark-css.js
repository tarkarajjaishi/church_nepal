// Generate the dark-mode semantic-colour bridge for the church site.
// Emits ONLY .dark-scoped rules so light mode is provably unchanged.
const fs = require('fs')

// family -> [tint rgb (Tailwind 400), ink hex (Tailwind 300)]
const FAMS = {
  green:   ['74, 222, 128',  '#86efac'],
  emerald: ['52, 211, 153',  '#6ee7b7'],
  teal:    ['45, 212, 191',  '#5eead4'],
  red:     ['248, 113, 113', '#fca5a5'],
  rose:    ['251, 113, 133', '#fda4af'],
  pink:    ['244, 114, 182', '#f9a8d4'],
  yellow:  ['250, 204, 21',  '#fde047'],
  amber:   ['251, 191, 36',  '#fcd34d'],
  orange:  ['251, 146, 60',  '#fdba74'],
  blue:    ['96, 165, 250',  '#93c5fd'],
  sky:     ['56, 189, 248',  '#7dd3fc'],
  indigo:  ['129, 140, 248', '#a5b4fc'],
  purple:  ['192, 132, 252', '#d8b4fe'],
  violet:  ['167, 139, 250', '#c4b5fd'],
  cyan:    ['34, 211, 238',  '#67e8f9'],
  lime:    ['163, 230, 53',  '#bef264'],
  fuchsia: ['232, 121, 249', '#f0abfc'],
}

// Shades actually used in the codebase, per role.
const TINT_BG = [50, 100, 200]          // pale chip/badge backgrounds
const INK_TEXT = [600, 700, 800, 900]   // dark text meant to sit on those chips
const TINT_BORDER = [100, 200, 300]

const target = 'C:/Tarkaproject/church_nepal/nextjs/app/globals.css'
let css0 = fs.readFileSync(target, 'utf8')
const MARK0 = '/* ---- Semantic status colours in dark mode'
const cut = css0.indexOf(MARK0)
const beforeBlock = cut === -1 ? css0 : css0.slice(0, cut)

// Classes the unscoped master bridge already owns (it maps blue/indigo to the
// brand colour on purpose, so the Theme Customizer can recolour them). A
// .dark-scoped rule here would out-specify that and silently take it over.
const OWNED = new Set(
  [...beforeBlock.matchAll(/\[class~="([^"]+)"\]/g)].map(m => m[1])
)

const sel = (list, fam, prefix) => {
  const kept = list.filter(s => !OWNED.has(`${prefix}-${fam}-${s}`))
  return kept.length
    ? kept.map(s => `.dark [class~="${prefix}-${fam}-${s}"]`).join(',\n')
    : null
}

let out = `
/* ---- Semantic status colours in dark mode ---------------------------------
   Status chips across the site are built from literal Tailwind palette
   classes: a pale background (bg-green-100) with dark text on top
   (text-green-800). 14 colour families, ~400 usages, none of them
   theme-aware — so in dark mode every badge stayed a bright pastel block with
   near-black text, sitting on a dark page. That is the "colours don't match
   the theme" problem: not a contrast failure (the pale/dark pairing is
   internally readable) but a surface that ignores the page it is on.

   Inverting the pairing per family keeps the semantic meaning (green = good,
   red = bad) while matching the dark surface: the background becomes a
   translucent tint of the same hue and the text becomes the light shade.
   Translucency means the chip picks up whatever card it sits on.

   Every rule is scoped to .dark, so light mode is byte-for-byte unchanged.
   Solid saturated backgrounds (bg-*-500/600/700, which carry white text) are
   deliberately left alone — they read correctly in both modes.

   Generated by scratchpad/gen-semantic.js — regenerate rather than hand-edit. */

.dark {
`
for (const [fam, [rgb, ink]] of Object.entries(FAMS)) {
  out += `  --tint-${fam}: rgba(${rgb}, 0.16);\n  --ink-${fam}: ${ink};\n`
}
out += `}\n`

let skipped = 0
for (const [fam, [rgb]] of Object.entries(FAMS)) {
  const bg = sel(TINT_BG, fam, 'bg')
  const tx = sel(INK_TEXT, fam, 'text')
  const bd = sel(TINT_BORDER, fam, 'border')
  out += '\n'
  if (bg) out += `${bg} { background-color: var(--tint-${fam}) !important; }\n`
  if (tx) out += `${tx} { color: var(--ink-${fam}) !important; }\n`
  if (bd) out += `${bd} { border-color: rgba(${rgb}, 0.32) !important; }\n`
}
for (const fam of Object.keys(FAMS))
  for (const [list, p] of [[TINT_BG, 'bg'], [INK_TEXT, 'text'], [TINT_BORDER, 'border']])
    skipped += list.filter(s => OWNED.has(`${p}-${fam}-${s}`)).length

fs.writeFileSync(target, beforeBlock.replace(/\s+$/, '') + '\n' + out)
console.log(`families: ${Object.keys(FAMS).length}, skipped (owned by master bridge): ${skipped}`)
